package report

import (
	"encoding/csv"
	"fmt"
	"io"

	"github.com/hrodrig/gghstats/internal/store"
)

// CSV writes traffic data as CSV to w.
func CSV(w io.Writer, repo string, views, clones []store.DayRow, refs []store.ReferrerRow, paths []store.PathRow) error {
	cw := csv.NewWriter(w)
	defer cw.Flush()

	if err := writeDaySection(cw, "# Views", []string{"date", "views", "unique_visitors"}, views); err != nil {
		return err
	}
	if err := writeDaySection(cw, "# Clones", []string{"date", "clones", "unique_cloners"}, clones); err != nil {
		return err
	}
	if err := writeReferrerSection(cw, refs); err != nil {
		return err
	}
	if err := writePathSection(cw, paths); err != nil {
		return err
	}

	return cw.Error()
}

func writeDaySection(cw *csv.Writer, title string, header []string, rows []store.DayRow) error {
	if err := writeSectionTitleAndHeader(cw, title, header); err != nil {
		return err
	}
	for _, r := range rows {
		if err := cw.Write([]string{r.Date, itoa(r.Count), itoa(r.Uniques)}); err != nil {
			return err
		}
	}
	return cw.Write(nil)
}

func writeReferrerSection(cw *csv.Writer, refs []store.ReferrerRow) error {
	if len(refs) == 0 {
		return nil
	}
	if err := writeSectionTitleAndHeader(cw, "# Referrers", []string{"date", "referrer", "count", "uniques"}); err != nil {
		return err
	}
	for _, r := range refs {
		if err := cw.Write([]string{r.Date, sanitizeCSVCell(r.Referrer), itoa(r.Count), itoa(r.Uniques)}); err != nil {
			return err
		}
	}
	return cw.Write(nil)
}

func writePathSection(cw *csv.Writer, paths []store.PathRow) error {
	if len(paths) == 0 {
		return nil
	}
	if err := writeSectionTitleAndHeader(cw, "# Popular Paths", []string{"date", "path", "title", "count", "uniques"}); err != nil {
		return err
	}
	for _, p := range paths {
		if err := cw.Write([]string{p.Date, sanitizeCSVCell(p.Path), sanitizeCSVCell(p.Title), itoa(p.Count), itoa(p.Uniques)}); err != nil {
			return err
		}
	}
	return nil
}

func writeSectionTitleAndHeader(cw *csv.Writer, title string, header []string) error {
	if err := cw.Write([]string{title}); err != nil {
		return err
	}
	return cw.Write(header)
}

// sanitizeCSVCell neutralizes spreadsheet formula injection (OWASP CSV
// Injection): Excel, Google Sheets and LibreOffice evaluate a cell whose text
// starts with =, +, -, @, TAB or CR as a formula when the CSV is opened.
// Prefixing the value with a single quote keeps it readable and inert in every
// spreadsheet app.
//
// Referrers, paths and titles come from GitHub and are therefore attacker
// controlled: anybody able to link a repository chooses the referrer and the
// page title that the operator later opens in a spreadsheet. Dates and counts
// are generated by gghstats and never start with those characters, so they are
// written as is.
func sanitizeCSVCell(s string) string {
	if s == "" {
		return s
	}
	switch s[0] {
	case '=', '+', '-', '@', '\t', '\r':
		return "'" + s
	}
	return s
}

func itoa(n int) string {
	return fmt.Sprintf("%d", n)
}
